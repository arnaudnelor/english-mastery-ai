class WritingIn(BaseModel):
    texts: dict[str, str] = Field(default_factory=dict)
    answers: dict[str, str] = Field(default_factory=dict)  # objective writing items (Build a Sentence)
    seconds: int = Field(0, ge=0, le=14400)


@router.post("/{pid}/attempts/{aid}/sections/{sid}/writing")
@provider_errors
def writing(pid: str, aid: int, sid: str, body: WritingIn, p: Profile = Depends(current_profile), db: Session = Depends(get_db)):
    paper = _paper(pid)
    a = _attempt(db, p, aid, pid)
    sec = _section(paper, sid)
    if sec["scoring"] != "writing":
        raise HTTPException(400, "Not a writing section")
    objective_review = [r for part in sec["parts"] if part["type"] == "build_sentence" for r in score_objective_part(part, body.answers)]
    tasks = [t for part in sec["parts"] if part["type"] == "writing" for t in part["tasks"]]
    text = "\n\n".join(f"TASK '{t['id']}' (minimum {t['min_words']} words)\nPROMPT: {t['prompt']}\nANSWER:\n{body.texts.get(t['id']) or '(no answer)'}" for t in tasks)
    r = get_llm().chat_json([
        ChatMessage("system", WRITING_RUBRIC[paper["kind"]] + ' Return strict JSON: {"tasks": {"<task id>": {"score": float, "criteria": {"<name>": float}, '
                    '"feedback": str, "key_errors": [{"original": str, "corrected": str, "explanation": str}]}}, "improvements": [str]}. '
                    "Penalise answers below the minimum length."),
        ChatMessage("user", text),
    ], max_tokens=3000)
    task_pcts = [max(0.0, min(1.0, float((r.get("tasks", {}).get(t["id"]) or {}).get("score") or 0) / 5)) for t in tasks]
    parts = task_pcts + ([sum(x["correct"] for x in objective_review) / len(objective_review)] if objective_review else [])
    pct = sum(parts) / len(parts)
    result = {"pct": round(pct, 3), "score": scales.section_score(pct, paper["kind"]), "tasks": r.get("tasks", {}),
              "improvements": r.get("improvements", []), "objective_review": objective_review}
    _save(db, a, sid, result)
    db.add(ActivityLog(profile_id=p.id, skill="writing", item_id=f"paper:{pid}:{aid}", score=pct, seconds=body.seconds))
    db.commit()
    return result


SPEAKING_PROMPT = {
    "toefl2026": "You are a TOEFL iBT speaking rater (2026 'Take an Interview' task).",
    "cambridge_c1": "You are a Cambridge C1 Advanced speaking examiner (criteria: Grammatical Resource, Lexical Resource, Discourse Management, Pronunciation, Interactive Communication).",
    "cambridge_c2": "You are a Cambridge C2 Proficiency speaking examiner (criteria: Grammatical Resource, Lexical Resource, Discourse Management, Pronunciation, Interactive Communication).",
}


@router.post("/{pid}/attempts/{aid}/sections/{sid}/speaking")
@provider_errors
async def speaking(pid: str, aid: int, sid: str, request: Request, p: Profile = Depends(current_profile), db: Session = Depends(get_db)):
    """Multipart form: one audio file per item, field name = '<part id>:<item id>'.
    Optional 'transcript:<part>:<item>' / 'duration:<part>:<item>' fields carry the browser's own recognition."""
    paper = _paper(pid)
    a = _attempt(db, p, aid, pid)
    sec = _section(paper, sid)
    if sec["scoring"] != "speaking":
        raise HTTPException(400, "Not a speaking section")
    form = await request.form()
    repeat_scores, answers, total = [], [], 0
    for part in sec["parts"]:
        for it in part["items"]:
            up = form.get(f"{part['id']}:{it['id']}")
            data = await up.read() if up is not None and hasattr(up, "read") else b""
            if len(data) > 25 * 1024 * 1024:
                raise HTTPException(413, "Recording too long")
            key = f"{part['id']}:{it['id']}"
            tx = str(form.get(f"transcript:{key}") or "")
            du = float(form.get(f"duration:{key}") or 0)
            t = transcribe_any(data, "speech.webm", tx, du) if (data or tx) else None
            m = fluency_metrics(t) if t else None
            total += int((m or {}).get("duration_sec") or 0)
            if part["type"] == "speaking_repeat":
                al = align(it["text"], t.text if t else "")
                repeat_scores.append({"id": it["id"], "target": it["text"], "heard": t.text if t else "", "score": al["score"], "words": al["words"]})
            else:
                answers.append({"id": it["id"], "question": it["question"], "transcript": t.text if t else "", "metrics": m})
    pcts = []
    if repeat_scores:
        pcts.append(sum(r["score"] for r in repeat_scores) / len(repeat_scores))
    llm_result = None
    if answers:
        if not any(x["transcript"] for x in answers):
            pcts.append(0.0)
        else:
            body = "\n\n".join(f"Q: {x['question']}\nTRANSCRIPT: {x['transcript'] or '(no answer)'}\nMETRICS: {x['metrics']}" for x in answers)
            llm_result = get_llm().chat_json([
                ChatMessage("system", SPEAKING_PROMPT[paper["kind"]] + " Transcripts come from speech recognition (ignore punctuation). "
                            'Return strict JSON: {"score": float (0-5), "criteria": {"<name>": float}, "feedback": str, "strengths": [str], "improvements": [str]}. '
                            "Pronunciation can only be estimated from recognition quality and metrics — say so."),
                ChatMessage("user", body)], max_tokens=1500)
            pcts.append(max(0.0, min(1.0, float(llm_result.get("score") or 0) / 5)))
    if not pcts:
        raise HTTPException(422, "No recordings received")
    pct = sum(pcts) / len(pcts)
    result = {"pct": round(pct, 3), "score": scales.section_score(pct, paper["kind"]), "repeat": repeat_scores,
              "answers": answers, "assessment": llm_result}
    _save(db, a, sid, result)
    db.add(ActivityLog(profile_id=p.id, skill="speaking", item_id=f"paper:{pid}:{aid}", score=pct, seconds=total + 60))
    db.commit()
    return result


@router.post("/{pid}/attempts/{aid}/finish")
def finish(pid: str, aid: int, p: Profile = Depends(current_profile), db: Session = Depends(get_db)):
    paper = _paper(pid)
    a = _attempt(db, p, aid, pid)
    res = a.results or {}
    done = {s["id"]: res[s["id"]]["score"] for s in paper["sections"] if s["id"] in res}
    if not done:
        raise HTTPException(400, "Complete at least one section first.")
    o = scales.overall(list(done.values()), paper["kind"])
    weakest = min(done, key=lambda k: res[k]["pct"])
    summary = {"sections": done, **o, "complete": len(done) == len(paper["sections"]), "weakest": weakest, "disclaimer": DISCLAIMER}
    a.results = {**res, "summary": summary}
    a.overall_band = float(o["overall"])
    a.finished_at = datetime.utcnow()
    db.commit()
    return summary
