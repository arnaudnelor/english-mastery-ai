router = APIRouter(prefix="/api/exam", tags=["exam"])
DISCLAIMER = "Practice estimate generated by English Mastery AI. It is not an official IELTS score."


def _exam(eid: str) -> dict:
    e = content.by_id(content.exams(), eid)
    if not e:
        raise HTTPException(404, "Exam not found")
    return e


def _questions(section: str, e: dict) -> list[tuple[str, dict, str]]:
    """(key, question, source_id) for every objective question in the section."""
    out = []
    if section == "listening":
        for iid in e["sections"]["listening"]["items"]:
            for q in content.exam_listening(iid)["questions"]:
                out.append((f"{iid}:{q['id']}", q, iid))
    else:
        for tid in e["sections"]["reading"]["texts"]:
            for q in content.exam_reading(tid)["questions"]:
                out.append((f"{tid}:{q['id']}", q, tid))
    return out


@router.get("/exams")
def list_exams():
    return [{"id": e["id"], "title": e["title"], "kind": e["kind"]} for e in content.exams()]


@router.get("/exams/{eid}")
def get_exam(eid: str):
    e = _exam(eid)
    s = e["sections"]
    strip = lambda q: {k: v for k, v in q.items() if k not in ("answer", "explanation")}  # noqa: E731
    listening = []
    for iid in s["listening"]["items"]:
        it = content.exam_listening(iid)
        listening.append({"id": iid, "title": it["title"], "kind": it["kind"], "speakers": it["speakers"], "lines": it["lines"], "level": it["level"],
                          "questions": [strip(q) | {"key": f"{iid}:{q['id']}"} for q in it["questions"]]})
    reading = []
    for tid in s["reading"]["texts"]:
        t = content.exam_reading(tid)
        reading.append({"id": tid, "title": t["title"], "body": t["body"],
                        "questions": [strip(q) | {"key": f"{tid}:{q['id']}"} for q in t["questions"]]})
    return {"id": e["id"], "title": e["title"], "disclaimer": DISCLAIMER,
            "listening": {"minutes": s["listening"]["minutes"], "parts": listening},
            "reading": {"minutes": s["reading"]["minutes"], "passages": reading},
            "writing": s["writing"], "speaking": s["speaking"]}


class StartIn(BaseModel):
    exam_id: str


@router.post("/attempts")
def start(body: StartIn, p: Profile = Depends(current_profile), db: Session = Depends(get_db)):
    _exam(body.exam_id)
    a = ExamAttempt(profile_id=p.id, exam_id=body.exam_id, results={})
    db.add(a)
    db.commit()
    return {"attempt_id": a.id}


def _attempt(db, p, aid) -> ExamAttempt:
    a = db.get(ExamAttempt, aid)
    if not a or a.profile_id != p.id:
        raise HTTPException(404, "Attempt not found")
    if a.finished_at:
        raise HTTPException(409, "This attempt is already finished")
    return a


def _save(db, a: ExamAttempt, section: str, result: dict):
    a.results = {**(a.results or {}), section: result}  # reassign so SQLAlchemy sees the change
    db.commit()


class ObjectiveIn(BaseModel):
    section: str = Field(pattern=r"^(listening|reading)$")
    answers: dict[str, str]
    seconds: int = Field(0, ge=0, le=7200)


@router.post("/attempts/{aid}/objective")
def objective(aid: int, body: ObjectiveIn, p: Profile = Depends(current_profile), db: Session = Depends(get_db)):
    a = _attempt(db, p, aid)
    qs = _questions(body.section, _exam(a.exam_id))
    review = []
    for key, q, _ in qs:
        given = body.answers.get(key, "")
        ok = content.normalise(given) == content.normalise(q["answer"])
        review.append({"key": key, "prompt": q["prompt"], "given": given, "answer": q["answer"], "correct": ok, "explanation": q["explanation"]})
    correct = sum(r["correct"] for r in review)
    band = objective_band(correct, len(qs))
    result = {"correct": correct, "total": len(qs), "band": band, "review": review}
    _save(db, a, body.section, result)
    db.add(ActivityLog(profile_id=p.id, skill=body.section, item_id=f"exam:{aid}", score=correct / len(qs), seconds=body.seconds))
    db.commit()
    return result


WRITING_PROMPT = """You are a certified IELTS Academic writing examiner. Assess both tasks strictly using the public \
IELTS band descriptors. Return strict JSON:
{"task1": {"task_achievement": float, "coherence_cohesion": float, "lexical_resource": float, "grammatical_range_accuracy": float,
           "band": float, "word_count": int, "feedback": str, "key_errors": [{"original": str, "corrected": str, "explanation": str}]},
 "task2": {"task_response": float, "coherence_cohesion": float, "lexical_resource": float, "grammatical_range_accuracy": float,
           "band": float, "word_count": int, "feedback": str, "key_errors": [{"original": str, "corrected": str, "explanation": str}]},
 "improvements": [str]}
Bands in 0.5 steps (0-9). Penalise under-length answers (Task 1 < 150 words, Task 2 < 250 words) as the descriptors require."""


class WritingIn(BaseModel):
    task1: str = Field("", max_length=8000)
    task2: str = Field("", max_length=12000)
    seconds: int = Field(0, ge=0, le=7200)


@router.post("/attempts/{aid}/writing")
@provider_errors
def writing(aid: int, body: WritingIn, p: Profile = Depends(current_profile), db: Session = Depends(get_db)):
    a = _attempt(db, p, aid)
    w = _exam(a.exam_id)["sections"]["writing"]
    chart = w["task1"]["chart"]
    data = "; ".join(f"{s['name']}: " + ", ".join(f"{c} {v}" for c, v in zip(chart["categories"], s["values"])) for s in chart["series"])
    r = get_llm().chat_json([
        ChatMessage("system", WRITING_PROMPT),
        ChatMessage("user", f"TASK 1 PROMPT: {w['task1']['prompt']}\nCHART DATA ({chart['title']}): {data}\n\nTASK 1 ANSWER:\n{body.task1 or '(no answer)'}\n\n"
                            f"TASK 2 PROMPT: {w['task2']['prompt']}\n\nTASK 2 ANSWER:\n{body.task2 or '(no answer)'}"),
    ], max_tokens=3000)
    t1 = float(r.get("task1", {}).get("band") or 0)
    t2 = float(r.get("task2", {}).get("band") or 0)
    r["band"] = half((t1 + 2 * t2) / 3)  # Task 2 counts double
    _save(db, a, "writing", r)
    for t in ("task1", "task2"):
        for e in (r.get(t, {}).get("key_errors") or [])[:10]:
            db.add(Mistake(profile_id=p.id, category="grammar", pattern=(e.get("original") or "")[:60], original=e.get("original", ""),
                           corrected=e.get("corrected", ""), explanation=e.get("explanation", ""), source="ielts_writing"))
    db.add(ActivityLog(profile_id=p.id, skill="writing", item_id=f"exam:{aid}", score=r["band"] / 9, seconds=body.seconds))
    db.commit()
    return r


SPEAKING_PROMPT = """You are a certified IELTS speaking examiner. You receive transcripts of a candidate's answers \
(from speech recognition, so ignore punctuation) plus objective timing metrics. Assess with the public descriptors. Return strict JSON:
{"fluency_coherence": float, "lexical_resource": float, "grammatical_range_accuracy": float, "pronunciation": float,
 "band": float, "feedback": str, "strengths": [str], "improvements": [str],
 "better_answers": [{"question": str, "model_phrases": [str]}]}
Bands in 0.5 steps. Pronunciation can only be estimated from recognition quality and the metrics: be cautious and say so in feedback."""


@router.post("/attempts/{aid}/speaking")
@provider_errors
def speaking(
    aid: int,
    part1: UploadFile = File(...),
    part2: UploadFile = File(...),
    part3: UploadFile = File(...),
    transcript_part1: str = Form(""), transcript_part2: str = Form(""), transcript_part3: str = Form(""),
    duration_part1: float = Form(0), duration_part2: float = Form(0), duration_part3: float = Form(0),
    p: Profile = Depends(current_profile),
    db: Session = Depends(get_db),
):
    a = _attempt(db, p, aid)
    sp = _exam(a.exam_id)["sections"]["speaking"]
    parts, total_secs = [], 0
    texts = {"part1": (transcript_part1, duration_part1), "part2": (transcript_part2, duration_part2), "part3": (transcript_part3, duration_part3)}
    questions = {"part1": " / ".join(sp["part1"]), "part2": sp["part2"]["topic"], "part3": " / ".join(sp["part3"])}
    for name, up in (("part1", part1), ("part2", part2), ("part3", part3)):
        data = up.file.read()
        if len(data) > 25 * 1024 * 1024:
            raise HTTPException(413, f"{name} recording too long")
        tx, du = texts[name]
        t = transcribe_any(data, up.filename or f"{name}.webm", tx, du) if (data or tx) else None
        m = fluency_metrics(t) if t else None
        total_secs += int((m or {}).get("duration_sec") or 0)
        parts.append({"part": name, "question": questions[name], "transcript": t.text if t else "", "metrics": m})
    if not any(x["transcript"] for x in parts):
        raise HTTPException(422, "No speech was recognised in any part.")
    body = "\n\n".join(f"{x['part'].upper()} (questions: {x['question']})\nTRANSCRIPT: {x['transcript'] or '(silence)'}\nMETRICS: {x['metrics']}" for x in parts)
    r = get_llm().chat_json([ChatMessage("system", SPEAKING_PROMPT), ChatMessage("user", body)], max_tokens=2000)
    r["band"] = half(float(r.get("band") or 0))
    r["parts"] = parts
    _save(db, a, "speaking", r)
    db.add(ActivityLog(profile_id=p.id, skill="speaking", item_id=f"exam:{aid}", score=r["band"] / 9, seconds=total_secs + 120))
    db.commit()
    return r


@router.post("/attempts/{aid}/finish")
def finish(aid: int, p: Profile = Depends(current_profile), db: Session = Depends(get_db)):
    a = _attempt(db, p, aid)
    res = a.results or {}
    bands = {s: res[s]["band"] for s in ("listening", "reading", "writing", "speaking") if s in res}
    if not bands:
        raise HTTPException(400, "Complete at least one section first.")
    overall = round_band(sum(bands.values()) / len(bands))
    weakest = min(bands, key=bands.get)
    tips = {
        "listening": "Do daily dictation in the Listening Lab at 1× speed without the transcript, and practise the lecture recording.",
        "reading": "Read one C1–C2 text a day under time pressure, and focus on inference and argument questions.",
        "writing": "Write one Task 2 essay a week in the Writing tutor, focusing on the criterion with your lowest score.",
        "speaking": "Use the IELTS Speaking mode in AI Conversation three times a week, with hands-free mode and strict corrections.",
    }
    a.overall_band = overall
    a.finished_at = datetime.utcnow()
    a.results = {**res, "summary": {"bands": bands, "overall": overall, "complete": len(bands) == 4,
                                    "weakest": weakest, "recommendation": tips[weakest],
                                    "target_gap": {s: round(7.0 - b, 1) for s, b in bands.items() if b < 7.0},
                                    "disclaimer": DISCLAIMER}}
    db.commit()
    return a.results["summary"]


@router.get("/attempts")
def history(p: Profile = Depends(current_profile), db: Session = Depends(get_db)):
    rows = db.scalars(select(ExamAttempt).where(ExamAttempt.profile_id == p.id).order_by(ExamAttempt.id.desc())).all()
    return [{"id": a.id, "exam_id": a.exam_id, "started_at": a.started_at.isoformat(), "finished": a.finished_at is not None,
             "overall_band": a.overall_band, "bands": (a.results or {}).get("summary", {}).get("bands")} for a in rows]
